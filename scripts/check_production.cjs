const { chromium } = require('../.tools/browser/node_modules/playwright');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const probe = require('node:net').createServer();
  await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  const base = `http://127.0.0.1:${port}`;
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'flow-production-smoke-'));
  const log = fs.openSync('.tools/production-browser-server.log', 'w');
  const server = spawn('.venv/bin/python', ['-m','uvicorn','studio.app:app','--host','127.0.0.1','--port',String(port)], {env:{...process.env,DIRECTOR_DATA:directory,DIRECTOR_NO_SEED:'1'},stdio:['ignore',log,log]});
  let browser;
  try {
    let ready=false;
    for(let i=0;i<80;i++) {if(server.exitCode!==null)throw new Error('Temporary server exited; see .tools/production-browser-server.log');try {const r=await fetch(`${base}/api/session`); if(r.ok){ready=true;break;}}catch{} await new Promise(r=>setTimeout(r,100));}
    assert(ready,'Temporary server did not start');
    browser=await chromium.launch({headless:true});
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    page.setDefaultTimeout(5000);
    await page.goto(`${base}/`);
    await page.getByRole('button',{name:/new project/i}).first().click();
    const flowMode = page.getByRole('button',{name:/Google Flow film/});
    await flowMode.waitFor();
    assert((await flowMode.getAttribute('class')).includes('active'), 'Flow must be the default');
    await page.getByLabel('Project title',{exact:true}).fill('Flow production browser fixture');
    await page.getByLabel('Topic',{exact:true}).fill('A robot learns gardening');
    await page.getByLabel('Audience',{exact:true}).fill('Curious adults');
    await page.getByLabel('Visual style',{exact:true}).fill('Illustrated');
    await page.getByLabel('Target duration (seconds)',{exact:true}).fill('24');
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    const handoff = page.getByRole('region',{name:'Production handoff'});
    await handoff.getByRole('heading',{name:'Production handoff'}).waitFor();
    await handoff.getByText('yt-script',{exact:true}).first().waitFor();
    assert(await handoff.getByText(/Generation adapter not connected/).isVisible());
    const projects=await (await fetch(`${base}/api/projects`)).json();
    assert.equal(projects.length,1);
    const id=projects[0].id;
    assert.equal(projects[0].settings.workflow_id,'comic-to-flow');
    assert.equal(projects[0].settings.production_brief.target_seconds,24);
    assert.equal(projects[0].settings.aspect_ratio,'9:16');
    await page.getByRole('button',{name:'Direction',exact:true}).click();
    await page.getByLabel('Creative locks',{exact:true}).fill('Keep the robot character consistent');
    const directionSaved = page.waitForResponse(r=>r.url()===`${base}/api/projects/${id}` && r.request().method()==='PATCH');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    assert.equal((await directionSaved).status(),200,'Flow creative direction must remain editable');
    await page.getByRole('heading',{name:'Project direction',exact:true}).waitFor({state:'hidden'});
    const directed=await (await fetch(`${base}/api/projects/${id}`)).json();
    assert.equal(directed.settings.creative_locks,'Keep the robot character consistent');
    assert.deepEqual(directed.settings.production_brief,projects[0].settings.production_brief);
    const filmPanel=page.getByRole('region',{name:'Film packages and credit limits',exact:true});
    await filmPanel.getByRole('heading',{name:'Film packages and credit limits',exact:true}).waitFor();
    await filmPanel.getByLabel('Project credit cap',{exact:true}).fill('75');
    await filmPanel.getByLabel('Budget decision note',{exact:true}).fill('Offline browser fixture cap');
    await filmPanel.getByLabel('Confirm this project credit cap',{exact:true}).check();
    await filmPanel.getByRole('button',{name:'Save credit cap',exact:true}).click();
    await filmPanel.getByText('Project cap: 75 credits',{exact:true}).waitFor();
    const script = `import json\nfrom studio import agent_tools as t\np=${JSON.stringify(id)}\nc=t.claim_task(p,'production-browser-fixture')\nr=t.run_youtube_tool(p,'hookscore',['--hook','You waste 3 hours editing: what if one cut fixed it?'],c['task_id'],c['token'])\nprint(json.dumps({'version_id':r['version_id']}))\n`;
    let saved;
    await new Promise((resolve,reject)=>{const child=spawn('.venv/bin/python',['-c',script],{env:{...process.env,DIRECTOR_DATA:directory},stdio:['ignore','pipe','pipe']});let stdout='',stderr='';child.stdout.on('data',x=>stdout+=x);child.stderr.on('data',x=>stderr+=x);child.on('exit',code=>{if(code===0){saved=JSON.parse(stdout);resolve();}else reject(new Error(stderr));});});
    await page.reload();
    await handoff.getByText('hookscore',{exact:true}).waitFor();
    await handoff.getByText('Output recorded',{exact:true}).first().waitFor();
    const project=await (await fetch(`${base}/api/projects/${id}`)).json();
    assert.equal(project.stage_status[0].complete,false);
    assert.equal(project.artifacts[0].latest.id,saved.version_id);
    assert.equal(project.artifacts[0].latest.status,'draft');
    assert((await page.getByRole('textbox',{name:'Generation prompt',exact:true}).inputValue()).includes('hookscore'));
    const receiptUrl = await handoff.getByRole('link',{name:'Download receipt',exact:true}).getAttribute('href');
    const receiptResponse = await fetch(`${base}${receiptUrl}`);
    assert.equal(receiptResponse.status,200);
    const receipt = await receiptResponse.json();
    assert.equal(receipt.youtube_execution.tool_name,'hookscore');
    assert.equal(receipt.result[0].hook,'You waste 3 hours editing: what if one cut fixed it?');
    assert.equal(await page.getByText('Wan 3.0',{exact:true}).count(),0);
    assert.equal(await page.getByText('Allow Wan to expand the prompt',{exact:false}).count(),0);
    await page.screenshot({path:'.tools/production-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'.tools/production-mobile.png',fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
    await page.getByRole('button',{name:/new project/i}).first().click();
    await page.getByLabel('Project title',{exact:true}).fill('Long Flow browser fixture');
    await page.getByLabel('Topic',{exact:true}).fill('An original long story');
    await page.getByLabel('Audience',{exact:true}).fill('Curious adults');
    await page.getByLabel('Visual style',{exact:true}).fill('Illustrated');
    await page.getByLabel('Video format',{exact:true}).selectOption('long');
    await page.getByLabel('Target duration (seconds)',{exact:true}).fill('180');
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    await page.getByRole('heading',{name:'Long Flow browser fixture',exact:true}).waitFor();
    const all=await (await fetch(`${base}/api/projects`)).json();
    const long=all.find(p=>p.title==='Long Flow browser fixture');
    assert.equal(long.settings.production_brief.format,'long');
    assert.equal(long.settings.aspect_ratio,'16:9');
    assert.deepEqual(errors,[]);
    console.log('PASS: Flow default/intake, persisted Short and long briefs, relevant skill handoff, actual tool receipt, no gate advance, honest provider limits, desktop/mobile, no page errors.');
  } finally {if(browser)await browser.close(); if(server.exitCode===null){server.kill('SIGTERM'); await new Promise(r=>server.once('exit',r));} fs.closeSync(log);fs.rmSync(directory,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
